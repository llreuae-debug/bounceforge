/**
 * Build verification check:
 * Enforces that every hittable object type and hero material has a sound recipe.
 * BUILD FAILS if any object type, material or prop that can be hit has no sound recipe.
 */
export function verifySoundRegistryComplete(): { valid: boolean; missing: string[] } {
  const missing: string[] = [];

  for (const type of ALL_TUNED_OBJECT_TYPES) {
    if (!SOUND_REGISTRY[type]) {
      missing.push(`TunedObjectType: ${type}`);
    }
  }

  for (const mat of ALL_HERO_MATERIALS) {
    if (!SOUND_REGISTRY[mat]) {
      missing.push(`HeroMaterial: ${mat}`);
    }
  }

  for (const ev of ALL_CONTACT_EVENTS) {
    if (!SOUND_REGISTRY[ev]) {
      missing.push(`ContactEvent: ${ev}`);
    }
  }

  for (const decor of ALL_DECOR_PROPS) {
    if (!SOUND_REGISTRY[decor] || !SOUND_REGISTRY[decor].isDecor) {
      missing.push(`DecorProp: ${decor} (must exist and have isDecor: true)`);
    }
  }

  return {
    valid: missing.length === 0,
    missing,
  };
}

/**
 * Access a sound recipe safely. Throws if an unmapped hittable object is requested.
 */
export function getSoundRecipe(type: string): SoundRecipe {
  const recipe = SOUND_REGISTRY[type];
  if (!recipe) {
    throw new Error(`CRITICAL SOUND ENGINE ERROR: No sound recipe registered for object type "${type}".`);
  }
  return recipe;
}
