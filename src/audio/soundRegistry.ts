import { TunedObjectType, HeroMaterial } from '../marble3d/types';

export type SynthesisType =
  | 'modal'
  | 'fm'
  | 'filtered_noise'
  | 'physical_model'
  | 'granular'
  | 'subtractive'
  | 'additive';

export type SoundCategory =
  | 'glass'
  | 'crystal'
  | 'metal'
  | 'percussion'
  | 'toy'
  | 'gadget'
  | 'kinetic'
  | 'ambient'
  | 'sfx';

export interface SoundRecipe {
  id: string;
  displayName: string;
  synthesisType: SynthesisType;
  pitchRange: [number, number]; // [minHz, maxHz]
  baseFreq: number; // default Hz
  attack: number; // attack in seconds
  decay: number; // decay in seconds
  tail: number; // sustain tail in seconds
  brightness: number; // 0 to 1 (spectral overtone / filter cutoff factor)
  noiseLayer: number; // 0 to 1 (transient impact click factor)
  stereoWidth: number; // 0 to 1
  baseVolume: number; // normalized gain 0 to 1
  category: SoundCategory;
  isDecor?: boolean; // Decor props cannot be hit, marked isDecor: true
  description: string;
}

