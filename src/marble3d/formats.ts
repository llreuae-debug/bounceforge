export class ReelFormatService {
  /**
   * Retrieves a format definition by ID
   */
  static getFormat(id: ReelFormatId): ReelFormatDefinition | undefined {
    return REEL_FORMATS.find((f) => f.id === id);
  }

  /**
   * Returns all 5 presets belonging to a format
   */
  static getPresetsForFormat(formatId: ReelFormatId): FormatPresetDefinition[] {
    return FORMAT_PRESETS.filter((p) => p.formatId === formatId);
  }

  /**
   * Builds Embossed 3D Text Configuration for a given format
   */
  static generateEmbossedText(
    formatId: ReelFormatId,
    customTitle?: string,
    handle: string = '@BounceForge'
  ): EmbossedTextConfig {
    const fmt = this.getFormat(formatId);
    const title = customTitle || fmt?.defaultTitle || 'marble melody';

    let fontStyle: EmbossedTextConfig['fontStyle'] = 'script';
    let embossMode: EmbossedTextConfig['embossMode'] = 'embossed';
    let colorMode: EmbossedTextConfig['colorMode'] = 'same_as_wall';

    if (formatId === 'f5_night_beats') {
      fontStyle = 'bold_cartoon';
      colorMode = 'colored';
    } else if (formatId === 'f6_squeaky_orchestra' || formatId === 'f7_gadget_tones') {
      fontStyle = 'bold_cartoon';
      colorMode = 'slightly_lighter';
    } else if (formatId === 'f11_split_screen' || formatId === 'f12_interior_scene') {
      fontStyle = 'clean_sans';
      colorMode = 'same_as_wall';
    }

    return {
      titleText: title,
      reminders: ['like & follow', 'comment below 👇'],
      handleRepeats: 3,
      fontStyle,
      embossMode,
      depth: 0.05,
      colorMode,
      revealAnswerText: fmt?.endingType === 'reveal_answer' ? 'Answer Reveal' : undefined,
    };
  }
}
