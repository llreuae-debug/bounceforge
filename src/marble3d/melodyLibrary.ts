// Procedural Melody Generator for infinite fresh original compositions
export function generateProceduralMelody(seed: number, duration: number = 56, bpm: number = 112): MelodyNote[] {
  let s = seed % 2147483647;
  if (s <= 0) s += 2147483646;
  const rnd = () => {
    s = (s * 16807) % 2147483647;
    return (s - 1) / 2147483646;
  };

  const scale = [60, 62, 64, 65, 67, 69, 71, 72, 74, 76, 77, 79, 81, 83, 84]; // C Major 2 Octaves
  const bassNotes = [36, 41, 43, 45, 48];
  const beatSec = 60 / bpm;
  const notes: MelodyNote[] = [];

  let currentTime = 0.5;
  let currentPitchIdx = 4; // G4

  while (currentTime < duration - 2.0) {
    const isStep = rnd() < 0.65;
    if (isStep) {
      const step = rnd() < 0.5 ? 1 : -1;
      currentPitchIdx = Math.max(0, Math.min(scale.length - 1, currentPitchIdx + step));
    } else {
      // Leap
      currentPitchIdx = Math.floor(rnd() * scale.length);
    }

    const noteMidi = scale[currentPitchIdx];
    const rhythmChoices = [0.5, 0.5, 1.0, 0.25, 0.75];
    const durationBeats = rhythmChoices[Math.floor(rnd() * rhythmChoices.length)];
    const noteDuration = durationBeats * beatSec;

    notes.push({
      time: parseFloat(currentTime.toFixed(3)),
      duration: parseFloat((noteDuration * 0.85).toFixed(3)),
      midi: noteMidi,
      freq: midiToFreq(noteMidi),
      pitchName: midiToNoteName(noteMidi),
      velocity: 0.8 + rnd() * 0.15,
      lane: 0,
    });

    currentTime += noteDuration;
  }

  // Finale Downbeat
  const finaleTime = duration - 1.0;
  notes.push({
    time: parseFloat(finaleTime.toFixed(3)),
    duration: 1.8,
    midi: 72, // High C5
    freq: midiToFreq(72),
    pitchName: 'C5',
    velocity: 0.95,
    lane: 0,
  });

  // Generate Bass Lane
  let bassTime = 0.5;
  while (bassTime < duration - 1.5) {
    const bMidi = bassNotes[Math.floor(rnd() * bassNotes.length)];
    notes.push({
      time: parseFloat(bassTime.toFixed(3)),
      duration: parseFloat((beatSec * 2 * 0.9).toFixed(3)),
      midi: bMidi,
      freq: midiToFreq(bMidi),
      pitchName: midiToNoteName(bMidi),
      velocity: 0.85,
      lane: 1,
    });
    bassTime += beatSec * 2;
  }
  notes.push({
    time: parseFloat(finaleTime.toFixed(3)),
    duration: 2.2,
    midi: 36, // Low C2
    freq: midiToFreq(36),
    pitchName: 'C2',
    velocity: 0.95,
    lane: 1,
  });

  return notes;
}

// Parse user uploaded MIDI file
export async function parseMidiFile(arrayBuffer: ArrayBuffer): Promise<MelodyNote[]> {
  const midi = new Midi(arrayBuffer);
  const notes: MelodyNote[] = [];

  midi.tracks.forEach((track, trackIdx) => {
    track.notes.forEach((n) => {
      notes.push({
        time: n.time,
        duration: n.duration,
        midi: n.midi,
        freq: midiToFreq(n.midi),
        pitchName: n.name,
        velocity: n.velocity,
        lane: trackIdx < 3 ? trackIdx : 0,
      });
    });
  });

  // Sort chronologically
  notes.sort((a, b) => a.time - b.time);
  return notes;
}
